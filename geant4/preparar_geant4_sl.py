"""Build the isolated Geant4 project ~/CNN_Sphere_Sample/PEPI2_SL20 (20 modulator positions) for the Shepp-Logan + inserts phantom.

Source: ~/CNN_Sphere_Sample/PEPI2 (the 4 mm sphere simulation of the CNN paper). That source is NOT modified; it is copied
and patched here. Geometry (ellipsoids, inserts, materials) is generated from sl_phantom.py / sl_insertos.py, the same
definitions that produce the analytic ground truth, so the simulation and the GT cannot drift apart.

Changes in the copy:
  * phantom (10 nested G4Ellipsoid + 6 + 6 G4Tubs fibres + G4Box + 6 G4Orb) replaces the sphere, centre at z = 0
    (0.85 m from the source, 0.65 m from the detector, as the sphere); overlap check active on every phantom volume;
  * modulator material = real SiC (G4_Si 70.05 % + C 29.95 %, 3.21 g/cm3; the original has Ti and 4.93 g/cm3),
    125 um grains, 4 layers + cellulose backing, at z = -15 cm, as in the sphere runs;
  * hydroxyapatite density 3.961 -> 3.16 g/cm3 (the value of its delta table, HA_delta.txt);
  * macro commands (before /run/initialize):
        /SL/fantoma 1|0     phantom present (S) or absent (R)
        /SL/modulador 1|0   modulator present or replaced by air (geometry check runs)
        /SL/trasX, /SL/trasY <value> um   modulator transverse position (same for R_k and S_k)
        /SL/semilla N       random seed (the original time(NULL) gives equal seeds to runs started in the same second)
  * the double counting of RunAction (2 counts per photon) is kept, so the images are consistent with the sphere data.

Usage: python3 preparar_geant4_sl.py   (writes the project; does not compile or run anything)
"""
import os, re, shutil, glob, textwrap
import numpy as np
import sl_phantom as S
import sl_insertos as I

ORIG = os.path.expanduser('~/CNN_Sphere_Sample/PEPI2')
DEST = os.path.expanduser('~/CNN_Sphere_Sample/PEPI2_SL20')   # first version (2 positions) went to PEPI2_SL
ESCALA = 4.0                       # mm, as in fig_sl_gt.py / fig_sl_insertos.py
N_PRIM = 1_000_000_000             # primaries per image (as the sphere images of the paper)
N_CHECK = 200_000_000              # primaries per geometry-check image
# (trasX, trasY) um of the modulator, pairs 00..19 (list given by the user, 2026-11-04). 00 and 01 are the positions of
# the first project (PEPI2_SL), same seeds, so those four .raw can be copied into build/ and are skipped by correr.sh.
PASOS = [(-10, 20), (70, -50), (60, 80), (100, 40), (150, -200), (180, -260), (-180, -20), (-300, 120),
         (-300, -330), (-420, 190), (290, 470), (20, 470), (-500, 60), (-240, 370), (0, 370), (-450, 30),
         (210, -40), (-80, 80), (400, -100), (250, 500)]
HILOS = 30

G4MAT = {'PMMA': 'G4_PLEXIGLASS', 'Water': 'G4_WATER', 'Air': 'G4_AIR', 'Graphite': 'G4_GRAPHITE',
         'Cellulose': 'G4_CELLULOSE_CELLOPHANE', 'Hydroxyapatite': 'Hydroxyapatite', 'Alumina': 'Alumina'}


def sub1(texto, patron, nuevo, n=1):
    texto, k = re.subn(patron, nuevo, texto)
    if k != n:
        raise RuntimeError(f'{patron!r}: {k} replacements, expected {n}')
    return texto


def codigo_fantoma():
    """C++ body of PepiDetectorConstruction2::ConstructSheppLogan(), generated from the Python definitions."""
    E = S.elipsoides(ESCALA)
    L = ['  // generated by preparar_geant4_sl.py from sl_phantom.py and sl_insertos.py (scale %.3f mm); units mm' % ESCALA,
         '  const G4bool chk = true;',
         '  auto mat = [](const char* n) { G4Material* m = G4Material::GetMaterial(n);',
         '    if (!m) G4Exception("ConstructSheppLogan", "SL001", FatalException, n); return m; };',
         '  std::vector<G4LogicalVolume*> lv(10);']
    for i, e in enumerate(E):
        a, b, c = e['ax']
        L.append(f'  lv[{i}] = new G4LogicalVolume(new G4Ellipsoid("SL_E{i+1}", {a:.6f}*mm, {b:.6f}*mm, {c:.6f}*mm), '
                 f'mat("{G4MAT[I.MAT_SL[i]]}"), "SL_E{i+1}_LV");')
    for i, e in enumerate(E):
        madre = 'fWorldLogical' if S.PADRE[i] is None else f'lv[{S.PADRE[i]}]'
        cm = np.zeros(3) if S.PADRE[i] is None else E[S.PADRE[i]]['c']
        # the mother of 3..10 is 2, itself unrotated, so the relative position is a plain difference
        assert S.PADRE[i] is None or E[S.PADRE[i]]['phi'] == 0
        p = e['c'] - cm
        L.append(f'  {{ G4RotationMatrix r; r.rotateZ({e["phi"]:.4f}*deg);   // active rotation, as R(-phi) in sl_phantom._cuerda')
        L.append(f'    new G4PVPlacement(G4Transform3D(r, G4ThreeVector({p[0]:.6f}*mm, {p[1]:.6f}*mm, {p[2]:.6f}*mm)), '
                 f'lv[{i}], "SL_E{i+1}", {madre}, false, 0, chk); }}')
    c2 = E[1]['c']
    for k, e in enumerate(I.INSERTOS):
        n = f'SL_{e["grupo"].replace("-", "")}_{k:02d}'
        p = e['c'] - c2
        if e['tipo'] == 'cil':
            sol = f'new G4Tubs("{n}", 0., {e["r"]:.6f}*mm, {e["h"]:.6f}*mm, 0., 360.*deg)'
            rot = 'r.rotateX(-90.*deg);' if e['eje'] == 'y' else 'r.rotateY(90.*deg);'
        elif e['tipo'] == 'caja':
            hs = e['hs']
            sol = f'new G4Box("{n}", {hs[0]:.6f}*mm, {hs[1]:.6f}*mm, {hs[2]:.6f}*mm)'; rot = ''
        else:
            sol = f'new G4Orb("{n}", {e["r"]:.6f}*mm)'; rot = ''
        L.append(f'  {{ G4RotationMatrix r; {rot}')
        L.append(f'    new G4PVPlacement(G4Transform3D(r, G4ThreeVector({p[0]:.6f}*mm, {p[1]:.6f}*mm, {p[2]:.6f}*mm)), '
                 f'new G4LogicalVolume({sol}, mat("{G4MAT[e["mat"]]}"), "{n}_LV"), "{n}", lv[1], false, 0, chk); }}')
    L.append('  G4cout << "SL_PHANTOM built: 10 ellipsoids + %d inserts, scale %.3f mm" << G4endl;' % (len(I.INSERTOS), ESCALA))
    return '\n'.join(L)


def parchear_dc(t):
    t = sub1(t, r'#include "PepiDetectorConstruction2.hh"\n',
             '#include "PepiDetectorConstruction2.hh"\n#include "G4Ellipsoid.hh"\n#include "G4Orb.hh"\n'
             '#include "G4Transform3D.hh"\n#include "G4GenericMessenger.hh"\n#include "G4SystemOfUnits.hh"\n'
             'extern G4int gSLSemilla;\n')
    # messenger: created with the detector, before any macro command
    t = sub1(t, r'  fMessenger = new PepiDetectorMessenger\(this\);\n',
             '  fMessenger = new PepiDetectorMessenger(this);\n'
             '  fSLFantoma = 1; fSLModulador = 1;\n'
             '  fSLMessenger = new G4GenericMessenger(this, "/SL/", "Shepp-Logan phantom runs");\n'
             '  fSLMessenger->DeclareProperty("fantoma", fSLFantoma, "1 = phantom present (S), 0 = absent (R)");\n'
             '  fSLMessenger->DeclareProperty("modulador", fSLModulador, "1 = SiC modulator, 0 = modulator made of air");\n'
             '  fSLMessenger->DeclarePropertyWithUnit("trasX", "um", fTrasX, "modulator x shift");\n'
             '  fSLMessenger->DeclarePropertyWithUnit("trasY", "um", fTrasY, "modulator y shift");\n'
             '  fSLMessenger->DeclareProperty("semilla", gSLSemilla, "random seed (0 = time)");\n')
    # real SiC
    t = sub1(t, r'density1 = 4\.93\*g/cm3;', 'density1 = 3.21*g/cm3;')
    t = sub1(t, r'SiC ->AddMaterial\(Titanium, fractionmass=70\.05\*perCent\);', 'SiC ->AddMaterial(Silicon, fractionmass=70.05*perCent);')
    t = sub1(t, r'densityHPA = 3\.961\*g/cm3;', 'densityHPA = 3.16*g/cm3;')
    t = sub1(t, r'fSphereMaterial   = SiC;\n  fMuscleMaterial   = Cellulose;',
             'fSphereMaterial   = SiC;\n  fMuscleMaterial   = Cellulose;\n'
             '  if (!fSLModulador) { fSphereMaterial = Air; fMuscleMaterial = Air; }\n'
             '  G4cout << "SL_CONFIG fantoma " << fSLFantoma << " modulador " << fSLModulador << " tras "\n'
             '         << fTrasX/um << " " << fTrasY/um << " um, fTras " << fTras/cm << " cm, semilla " << gSLSemilla\n'
             '         << ", modulator " << fSphereMaterial->GetName() << " " << fSphereMaterial->GetDensity()/(g/cm3) << " g/cm3" << G4endl;')
    # sphere -> phantom
    i0 = t.index('fSphere8Solid = new G4Sphere("sphere8"')
    i1 = t.index('fCheckOverlaps);', t.index('fSphere8Physical = new G4PVPlacement')) + len('fCheckOverlaps);')
    t = t[:i0] + 'if (fSLFantoma) ConstructSheppLogan();   // replaces the 4 mm sphere (sphere8)\n' + t[i1:]
    t = sub1(t, r'  fSphere8Logical->SetVisAttributes\(sphere8VisAtt\);', '  if (fSphere8Logical) fSphere8Logical->SetVisAttributes(sphere8VisAtt);')
    t += '\n\nnamespace PEPI2\n{\nvoid PepiDetectorConstruction2::ConstructSheppLogan()\n{\n' + codigo_fantoma() + '\n}\n}\n'
    return t


def parchear_hh(t):
    t = sub1(t, r'\nnamespace PEPI2', '\nclass G4GenericMessenger;\n\nnamespace PEPI2')
    t = sub1(t, r'    void DefineVolumes\(\);', '    void DefineVolumes();\n    void ConstructSheppLogan();')
    t = sub1(t, r'    G4bool  fCheckOverlaps;', '    G4bool  fCheckOverlaps;\n    G4int fSLFantoma;\n    G4int fSLModulador;\n'
             '    G4GenericMessenger* fSLMessenger;')
    return t


def parchear_run(t):
    t = sub1(t, r'#include "RunAction.hh"\n', '#include "RunAction.hh"\n\nG4int gSLSemilla = 0;   // set by /SL/semilla\n')
    return sub1(t, r'fSeed = time\(NULL\);', 'fSeed = gSLSemilla ? gSLSemilla : time(NULL);\n'
                '  G4cout << "SL_SEED " << fSeed << G4endl;')


def macro(nombre, fantoma, modulador, tras, semilla, n):
    return textwrap.dedent(f'''\
        # {nombre}: Shepp-Logan + inserts, 28 keV mono, SiC 125 um modulator. Generated by preparar_geant4_sl.py
        /control/verbose 0
        /run/verbose 0
        /run/numberOfThreads {HILOS}
        /run/printProgress 100000000
        /control/execute detmask_config.in
        /Pepi/cont/loadConfig geometry_config.in
        /SL/fantoma {fantoma}
        /SL/modulador {modulador}
        /SL/trasX {tras[0]} um
        /SL/trasY {tras[1]} um
        /SL/semilla {semilla}
        /Pepi/cont/setBaseName {nombre}
        /run/initialize
        /control/execute gps.in
        /Pepi/cont/beamOn {n}
        ''')


def main():
    if os.path.exists(DEST):
        raise SystemExit(f'{DEST} already exists: remove it first (it is generated, nothing to keep there except build/*.raw)')
    for x in ('src', 'include'):
        shutil.copytree(f'{ORIG}/{x}', f'{DEST}/{x}')
    shutil.copy(f'{ORIG}/PEPI2.cc', DEST)
    os.makedirs(f'{DEST}/data'); os.makedirs(f'{DEST}/mac')
    datos = glob.glob(f'{ORIG}/data/*_[dD]elta.txt') + [f'{ORIG}/data/Energy.txt'] + \
        [f'{ORIG}/data/125_um_Coord{k}.txt' for k in ('', '2', '3', '4')]
    for f in datos:
        shutil.copy(f, f'{DEST}/data')
    for f in ('detmask_config.in', 'geometry_config.in', 'gps.in'):     # the ones the sphere runs used
        shutil.copy(f'{ORIG}/build/{f}', f'{DEST}/mac/{f}')

    f = f'{DEST}/src/PepiDetectorConstruction2.cc'; txt = parchear_dc(open(f).read()); open(f, 'w').write(txt)
    f = f'{DEST}/include/PepiDetectorConstruction2.hh'; txt = parchear_hh(open(f).read()); open(f, 'w').write(txt)
    f = f'{DEST}/src/RunAction.cc'; txt = parchear_run(open(f).read()); open(f, 'w').write(txt)

    macros = {'run_check_flat.mac': macro('SL_check_flat_28kev_', 0, 0, PASOS[0], 1101, N_CHECK),
              'run_check_fantoma.mac': macro('SL_check_fantoma_28kev_', 1, 0, PASOS[0], 1102, N_CHECK)}
    for k, tr in enumerate(PASOS):
        for rs, fan in (('R', 0), ('S', 1)):
            macros[f'run_{rs}{k:02d}.mac'] = macro(f'SL_{rs}{k:02d}_28kev_SiC125_', fan, 1, tr, 2000 + 10 * k + fan, N_PRIM)
    for n, m in macros.items():
        open(f'{DEST}/mac/{n}', 'w').write(m)

    archivos = sorted(os.listdir(f'{DEST}/mac'))
    open(f'{DEST}/CMakeLists.txt', 'w').write(textwrap.dedent('''\
        cmake_minimum_required(VERSION 3.16...3.21)
        project(PEPI2)
        find_package(Geant4 REQUIRED)
        include(${Geant4_USE_FILE})
        include_directories(${PROJECT_SOURCE_DIR}/include)
        file(GLOB sources ${PROJECT_SOURCE_DIR}/src/*.cc)
        file(GLOB headers ${PROJECT_SOURCE_DIR}/include/*.hh)
        add_executable(PEPI2 PEPI2.cc ${sources} ${headers})
        target_link_libraries(PEPI2 ${Geant4_LIBRARIES})
        # macros and configuration files go next to the executable; the code reads ../data/
        foreach(_f %s)
          configure_file(${PROJECT_SOURCE_DIR}/mac/${_f} ${PROJECT_BINARY_DIR}/${_f} COPYONLY)
        endforeach()
        ''' % ' '.join(archivos)))

    orden = ['run_check_flat.mac', 'run_check_fantoma.mac'] + [f'run_{rs}{k:02d}.mac' for k in range(len(PASOS)) for rs in 'RS']
    open(f'{DEST}/correr.sh', 'w').write(textwrap.dedent(f'''\
        #!/bin/bash
        # Compile (if needed) and run the Shepp-Logan images one after the other (one Geant4 process per image:
        # phantom on/off and modulator position are fixed at /run/initialize).
        # Usage:  bash correr.sh [threads] [macro ...]      e.g.  bash correr.sh 60   or   bash correr.sh 30 run_S00.mac
        # Default macros: {' '.join(orden)}
        set -e
        cd "$(dirname "$0")"
        H=${{1:-{HILOS}}}; shift || true
        M=("$@"); [ ${{#M[@]}} -eq 0 ] && M=({' '.join(orden)})
        mkdir -p build && cd build
        [ -x PEPI2 ] || {{ cmake .. > compilacion.log 2>&1 && make -j"$(nproc)" >> compilacion.log 2>&1; }}
        cmake .. > /dev/null                                   # refresh the macros copied into build/
        for m in "${{M[@]}}"; do
          base=$(grep -oP '(?<=setBaseName )\\S+' "$m")
          if ls "${{base}}"_d*.raw > /dev/null 2>&1; then echo "skip $m (${{base}}*.raw exists; .raw files are appended)"; continue; fi
          sed -i "s|^/run/numberOfThreads .*|/run/numberOfThreads $H|" "$m"
          echo "$(date '+%F %T') start $m ($H threads)"
          ./PEPI2 "$m" > "${{m%.mac}}.log" 2>&1
          grep -q "SL_CONFIG" "${{m%.mac}}.log" || {{ echo "ERROR: no SL_CONFIG line in ${{m%.mac}}.log"; exit 1; }}
          grep -i "overlap" "${{m%.mac}}.log" | grep -vi "OK" | head -5 || true
          echo "$(date '+%F %T') done  $m -> $(ls ${{base}}_d*.raw)"
        done
        '''))
    os.chmod(f'{DEST}/correr.sh', 0o755)
    print(f'project written to {DEST}')


if __name__ == '__main__':
    main()
